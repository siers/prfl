const StringArray = z.array(z.string())
const StringArrayArray = z.array(z.array(z.string()))

export function toInterpolateSubst(subst: any): InterpolateSubstT {
  const strings = StringArray.safeParse(subst)
  const strings2d = StringArrayArray.safeParse(subst)

  if (strings.success) return strings.data
  else if (strings2d.success) return strings2d.data.map(a => a.join('')) // each token-group joins to one value
  else return [subst?.toString() || '']
}

// A tag a multi-tag source returns: its name and flags, as a `[]` would carry
// them, and its values in any shape a single `[]` may return.
export type GeneratedTag = { tag: string, tags: string[] | null, contents: InterpolateSubstT }

const TagValues = z.union([z.string(), StringArray, StringArrayArray])
// The native shape: a Substitution, or any subset with a tag and contents.
const GeneratedTagSchema = z.object({ tag: z.string(), tags: StringArray.nullish(), contents: TagValues })
const GeneratedTagsRecordSchema = z.record(z.string(), z.union([TagValues, GeneratedTagSchema.omit({ tag: true })]))

// A source spits out several tags by returning either `{ name: values }` /
// `{ name: { contents, tags } }`, or an array of `{ tag, tags?, contents }`.
// Anything else is a single tag's values — null.
export function toGeneratedTags(out: any): GeneratedTag[] | null {
  const tag = (name: string, tags: string[] | null | undefined, contents: unknown): GeneratedTag =>
    ({ tag: name, tags: tags && tags.length > 0 ? tags : null, contents: toInterpolateSubst(contents) })

  const list = z.array(GeneratedTagSchema).safeParse(out)
  if (list.success && list.data.length > 0) return list.data.map(g => tag(g.tag, g.tags, g.contents))

  // Only plain objects: anything with its own prototype keeps rendering via toString.
  if (out === null || typeof out !== 'object' || Object.getPrototypeOf(out) !== Object.prototype) return null
  const record = GeneratedTagsRecordSchema.safeParse(out)
  if (!record.success) return null
  return Object.entries(record.data).map(([name, v]) =>
    typeof v === 'object' && !Array.isArray(v) ? tag(name, v.tags, v.contents) : tag(name, null, v))
}

export function rotateInterpolateSubst(s: InterpolateSubstT): InterpolateSubstT {
  return arrayShift(s, 1)
}

