// The text after the marker is an item line, parsed and evaluated like one; its
// key names the block. A bare marker leaves it null.
export type Header = {
  kind: 'header',
  line: Line | null,
  shuffle: boolean,
}

// Blocks emitted into the root deck: the bare-marker ones. A named block lands
// nowhere on its own — it's callable, and an item keyed with its name can
// instantiate it as a subdeck.
export const isMainHeader: (h: Header) => boolean = (h: Header) => h.line === null

// Each block's evaluated header, aligned with the parsed blocks: null for a main
// block, or for a named one whose header explode yielded nothing (it's dropped).
// Evaluated once, with the root deck, and reused from then on.
export type BlockHeaders = (RenderLine | null)[]

export type Item = Header | Line

// How a block orders its lines: `scheduled` sorts them least-recently-reviewed
// first (after the marker's shuffle), `shuffled` shuffles them whatever the
// marker, `unscheduled` keeps them as written. `unscheduleNew` schedules like
// `scheduled`, but the never-reviewed lines go first, in the block's order.
// Set by the `order` field (`#scheduled`, `#shuffled`, `#unscheduled`,
// `#unscheduleNew`).
export const BlockOrders = ['scheduled', 'shuffled', 'unscheduled', 'unscheduleNew'] as const
export type BlockOrder = typeof BlockOrders[number]

// A line's `order` field by its current value, or null without one.
export function orderField(l: RenderLine | null): BlockOrder | null {
  const field = l?.source?.substitutions?.find(s => s.tag === 'order')?.contents[0]
  return BlockOrders.find(o => o === field) ?? null
}

// Whether a block's lines are shuffled: by its order, else by the marker —
// `---` shuffles, `-=-` doesn't.
export function orderShuffles(order: BlockOrder | null, h: Header): boolean {
  return order === 'shuffled' || (order !== 'unscheduled' && h.shuffle)
}

